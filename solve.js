/** The characters a backslash escapes. */
const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);

/** The first index in s[from, hi) where `what` stands outside a backslash escape, or -1. */
function findUnescaped(s, what, from, hi) {
  const wlen = what.length;
  for (let j = from; j + wlen <= hi; j++) {
    if (s[j] === '\\' && j + 1 < hi && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

/** The first single * in s[from, hi) (one whose run is not **), outside an escape, or -1. */
function findSingleStar(s, from, hi) {
  for (let j = from; j < hi; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < hi && ESCAPABLE.has(s[j + 1])) { j++; continue; }
    if (c !== '*') continue;
    if (j + 1 < hi && s[j + 1] === '*') { j++; continue; }
    return j;
  }
  return -1;
}

/** The characters a backslash escapes, as a code table for the inline scanner. */
const ESCAPABLE_CODE = new Uint8Array(128);
for (const ch of ['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']) ESCAPABLE_CODE[ch.charCodeAt(0)] = 1;

/**
 * s[lo, hi) rendered inline into `out` (an array of string pieces); `env.link(target)` resolves a
 * link's href. Works on index ranges of the original string, so nested constructs never copy it.
 */
function renderInline(s, lo, hi, env, out) {
  let i = lo;
  let lit = lo; // the start of the plain run not yet written
  const flush = (upto) => { if (upto > lit) out.push(escapeHtml(s.slice(lit, upto))); };
  while (i < hi) {
    const c = s.charCodeAt(i);
    if (c === 92 && i + 1 < hi) { // backslash
      const nc = s.charCodeAt(i + 1);
      if (nc < 128 && ESCAPABLE_CODE[nc] === 1) {
        flush(i);
        out.push(escapeHtml(s[i + 1]));
        i += 2;
        lit = i;
        continue;
      }
      i++;
      continue;
    }
    if (c === 96) { // backtick
      let j = s.indexOf('`', i + 1);
      if (j >= hi) j = -1;
      if (j > i + 1) {
        flush(i);
        out.push('<code>', escapeHtml(s.slice(i + 1, j)), '</code>');
        i = j + 1;
        lit = i;
      } else {
        i++;
      }
      continue;
    }
    if (c === 42) { // star
      if (i + 1 < hi && s.charCodeAt(i + 1) === 42) {
        const j = findUnescaped(s, '**', i + 2, hi);
        if (j > i + 2) {
          flush(i);
          out.push('<strong>');
          renderInline(s, i + 2, j, env, out);
          out.push('</strong>');
          i = j + 2;
          lit = i;
        } else {
          i += 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1, hi);
      if (j > i + 1) {
        flush(i);
        out.push('<em>');
        renderInline(s, i + 1, j, env, out);
        out.push('</em>');
        i = j + 1;
        lit = i;
      } else {
        i++;
      }
      continue;
    }
    if (c === 91) { // [
      const k = findUnescaped(s, ']', i + 1, hi);
      let m = -1;
      if (k !== -1 && k + 1 < hi && s[k + 1] === '(') {
        m = s.indexOf(')', k + 2);
        if (m >= hi) m = -1;
      }
      const target = m === -1 ? '' : s.slice(k + 2, m);
      if (target !== '' && !/\s/.test(target)) {
        flush(i);
        out.push('<a href="', escapeHtml(env.link(target)), '">');
        renderInline(s, i + 1, k, env, out);
        out.push('</a>');
        i = m + 1;
        lit = i;
        continue;
      }
      i++;
      continue;
    }
    i++;
  }
  flush(hi);
}

/** `text` rendered inline to a string. */
function inlineText(text, env) {
  const out = [];
  renderInline(text, 0, text.length, env, out);
  return out.join('');
}

/** A line's fence opening: its language (possibly ""), or null when the line opens no fence. */
function fenceOpen(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

/** Whether `line` closes a fence: three backticks, then spaces or tabs only. */
function fenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

/** A heading line's depth and text, or null (a heading's text is never empty). */
function headingOf(line) {
  let depth = 0;
  while (depth < line.length && line.charCodeAt(depth) === 35) depth++;
  if (depth === 0 || depth > 6) return null;
  const c = line.charCodeAt(depth);
  if (c !== 32 && c !== 9) return null;
  let start = depth;
  while (start < line.length && (line.charCodeAt(start) === 32 || line.charCodeAt(start) === 9)) start++;
  let end = line.length;
  while (end > start && (line.charCodeAt(end - 1) === 32 || line.charCodeAt(end - 1) === 9)) end--;
  if (end === start) return null;
  return { depth, text: line.slice(start, end) };
}

/** Whether `line` is a thematic break: --- or ***, then spaces or tabs only. */
function isHr(line) {
  const c = line.charCodeAt(0);
  if (c !== 45 && c !== 42) return false;
  if (line.charCodeAt(1) !== c || line.charCodeAt(2) !== c) return false;
  for (let i = 3; i < line.length; i++) {
    const cc = line.charCodeAt(i);
    if (cc !== 32 && cc !== 9) return false;
  }
  return true;
}

/** Whether `line` ends a paragraph: blank, a fence, a heading or a thematic break. */
function endsParagraph(line) {
  if (isBlankLine(line)) return true;
  const c = line.charCodeAt(0);
  if (c === 96) return fenceOpen(line) !== null;
  if (c === 35) return headingOf(line) !== null;
  if (c === 45 || c === 42) return isHr(line);
  return false;
}

/** A line trimmed of spaces and tabs at both ends. */
function trimLine(line) {
  let a = 0;
  let b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return a === 0 && b === line.length ? line : line.slice(a, b);
}

/**
 * A list's first line: { ordered, start, text } or null. A bullet is "- " or "* "; an ordered
 * item is 1 to 9 digits, ". " and the text.
 */
function listHead(line) {
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) {
    return { ordered: false, start: 1, text: line.slice(2) };
  }
  if (c >= 48 && c <= 57) {
    let k = 0;
    while (k < line.length && line.charCodeAt(k) >= 48 && line.charCodeAt(k) <= 57) k++;
    if (k <= 9 && line.charCodeAt(k) === 46 && line.charCodeAt(k + 1) === 32) {
      return { ordered: true, start: Number(line.slice(0, k)), text: line.slice(k + 2) };
    }
  }
  return null;
}

/** A following line of a list of the same kind: its item text, or null. */
function listNext(line, ordered) {
  if (ordered) {
    const c = line.charCodeAt(0);
    if (c < 48 || c > 57) return null;
    let k = 0;
    while (k < line.length && line.charCodeAt(k) >= 48 && line.charCodeAt(k) <= 57) k++;
    if (k <= 9 && line.charCodeAt(k) === 46 && line.charCodeAt(k + 1) === 32) return line.slice(k + 2);
    return null;
  }
  const c = line.charCodeAt(0);
  if ((c === 45 || c === 42) && line.charCodeAt(1) === 32) return line.slice(2);
  return null;
}

/** Whether `line` continues a list item: two or more spaces, then a non-whitespace character. */
function isContinuation(line) {
  let k = 0;
  while (k < line.length && line.charCodeAt(k) === 32) k++;
  return k >= 2 && k < line.length && !isWs(line[k]);
}

/**
 * `src` rendered in one pass over its lines: its HTML (a "\n" after every block), its table of
 * contents (every level 2 and 3 heading) and its excerpt (the first paragraph's HTML, or "").
 * `slugify` is the build's memoised slug function.
 */
function renderMarkdown(src, env, slugify) {
  const lines = src.split('\n');
  const ids = new Set();
  const blocks = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  const n = lines.length;
  while (i < n) {
    const line = lines[i];
    if (isBlankLine(line)) { i++; continue; }
    const fence = fenceOpen(line);
    if (fence !== null) {
      i++;
      const parts = [];
      while (i < n && !fenceClose(lines[i])) { parts.push(escapeHtml(lines[i]), '\n'); i++; }
      i++;
      const cls = fence === '' ? '' : ` class="language-${escapeHtml(fence)}"`;
      blocks.push(`<pre><code${cls}>${parts.join('')}</code></pre>`);
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      const html = inlineText(heading.text, env);
      blocks.push(`<h${heading.depth} id="${id}">${html}</h${heading.depth}>`);
      if (heading.depth === 2 || heading.depth === 3) toc.push({ level: heading.depth, id, html });
      i++;
      continue;
    }
    if (isHr(line)) { blocks.push('<hr>'); i++; continue; }
    if (line.charCodeAt(0) === 62) {
      const body = [];
      while (i < n && lines[i].charCodeAt(0) === 62) {
        let l = lines[i];
        l = l.startsWith('> ') ? l.slice(2) : l.slice(1);
        body.push(l);
        i++;
      }
      const kept = [];
      for (const l of body) {
        const t = trimLine(l);
        if (t !== '') kept.push(t);
      }
      blocks.push(kept.length === 0 ? '<blockquote>\n</blockquote>' : `<blockquote>\n<p>${inlineText(kept.join('\n'), env)}</p>\n</blockquote>`);
      continue;
    }
    const head = listHead(line);
    if (head !== null) {
      const items = [[trimLine(head.text)]];
      i++;
      while (i < n) {
        const nx = listNext(lines[i], head.ordered);
        if (nx !== null) { items.push([trimLine(nx)]); i++; }
        else if (isContinuation(lines[i])) { items[items.length - 1].push(trimLine(lines[i])); i++; }
        else break;
      }
      const tag = head.ordered ? 'ol' : 'ul';
      const open = head.ordered && head.start !== 1 ? `<ol start="${head.start}">` : `<${tag}>`;
      const parts = [open, '\n'];
      for (const partsOfItem of items) {
        parts.push('<li>', inlineText(partsOfItem.join('\n'), env), '</li>\n');
      }
      parts.push(`</${tag}>`);
      blocks.push(parts.join(''));
      continue;
    }
    const body = [trimLine(line)];
    i++;
    while (i < n && !endsParagraph(lines[i])) { body.push(trimLine(lines[i])); i++; }
    const html = inlineText(body.join('\n'), env);
    if (excerpt === null) excerpt = html;
    blocks.push(`<p>${html}</p>`);
  }
  return { html: blocks.map((b) => `${b}\n`).join(''), toc, excerpt: excerpt ?? '' };
}

